    private void guardarProcesadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarProcesadoActionPerformed
        try {
            String ingredientes = listMXM.getText().trim();
            String codigo = codMXM.getText().trim();
            String nombre = namMXM.getText().trim();
            String proteinasPorCienGramosTexto = proteMXM.getText().trim();
            double proteinasDouble = Double.parseDouble(proteinasPorCienGramosTexto);
            String carbohidratosPorCienGramosTexto = carbMXM.getText().trim();
            double carbohidratosDouble = Double.parseDouble(carbohidratosPorCienGramosTexto);
            String grasasPorCienGramosTexto = grasMXM.getText().trim();
            double grasasDouble = Double.parseDouble(grasasPorCienGramosTexto);
            Date fechaCreacion = (Date) fecMXM.getValue();

            if (codigo.isEmpty() || nombre.isEmpty() || proteinasPorCienGramosTexto.isEmpty()
                    || carbohidratosPorCienGramosTexto.isEmpty() || grasasPorCienGramosTexto.isEmpty() || ingredientes.isEmpty()) {

            } else {

                boolean codigoExiste = false;
                for (AlimentoProcesado alimentoExistente : Lista.procesados) {
                    if (alimentoExistente.getCodigo().equalsIgnoreCase(codigo)) {
                        codigoExiste = true;
                        break;
                    }
                }
                if (codigoExiste) {
                    JOptionPane.showMessageDialog(null, "Ya existe un alimento con el mismo código. Por favor, ingresa un código distinto.");
                } else {
                    AlimentoProcesado alimento = new AlimentoProcesado(codigo, nombre, proteinasDouble, carbohidratosDouble, grasasDouble, (Date)fechaCreacion, ingredientes);
                    Lista.procesados.add(alimento);
                    Proyecto1.GuardarDatos();
                    JOptionPane.showMessageDialog(null, "Datos almacenados exitosamente.");
                    codMXM.setText("");
                    namMXM.setText("");
                    proteMXM.setText("");
                    carbMXM.setText("");
                    grasMXM.setText("");
                    listMXM.setText("");

                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Datos vacíos. Por favor, completa todos los campos.");

        }

    }//GEN-LAST:event_guardarProcesadoActionPerformed

