    private void buscarProcesadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarProcesadoActionPerformed
         String codigo = codMXM.getText().trim();
        boolean alimentoEncontrado = false; // Variable para indicar si se encontró el alimento

        for (int i = 0; i < Lista.procesados.size(); i++) {
            AlimentoProcesado alimento = Lista.procesados.get(i);
            
                if (alimento.getCodigo().equalsIgnoreCase(codigo)) {
                    alimentoEncontrado = true;

                    JOptionPane.showMessageDialog(null, "Alimento encontrado");

                    String ingredientes = listMXM.getText().trim();
                    codMXM.setText(alimento.getCodigo() + "");
                    namMXM.setText(alimento.getNombre() + "");
                    proteMXM.setText(alimento.getProteinasPorCienGramos() + "");
                    carbMXM.setText(alimento.getCarbohidratosPorCienGramos() + "");
                    grasMXM.setText(alimento.getGrasasPorCienGramos() + "");
                    fecMXM.setValue(alimento.getFechaCreacion());

                    break; // Salir del bucle una vez que se encuentra el alimento
                }
            
        }

        if (!alimentoEncontrado) {
            JOptionPane.showMessageDialog(null, "No se ha encontrado ningún código de alimento.");
            codMXM.setText("");
        }
    }//GEN-LAST:event_buscarProcesadoActionPerformed

